(** Inclusive convention: skeleton n is generated by degrees at most n.
    Thus skeleton 0 contains all vertices and their degeneracies. *)
Definition skeleton (X : simplicial_set) (n : nat) : subcomplex X :=
  generated_subcomplex (fun k (_ : simplex X k) => (k <= n)%N).

Lemma skeleton_member X n k (x : simplex X k) :
  member (skeleton X n) k x <->
    exists m (y : simplex X m) (f : ordinal_map k m),
      (m <= n)%N /\ simplex_map X f y = x.
Proof. reflexivity. Qed.

Lemma skeleton_contains_degree X n k (x : simplex X k) :
  (k <= n)%N -> member (skeleton X n) k x.
Proof.
  exact (@generated_contains X (fun l (_ : simplex X l) => (l <= n)%N) k x).
Qed.

Lemma skeleton_mono X n m : (n <= m)%N ->
  subcomplex_le (skeleton X n) (skeleton X m).
Proof.
  intro hnm. apply generated_mono. intros k x hkn. exact (leq_trans hkn hnm).
Qed.

Definition skeleton_set (X : simplicial_set) (n : nat) : simplicial_set :=
  subcomplex_set (skeleton X n).

Definition skeleton_inclusion (X : simplicial_set) (n : nat) :
  simplicial_map (skeleton_set X n) X := subcomplex_inclusion (skeleton X n).

Definition skeleton_transition X n m (h : (n <= m)%N) :
  simplicial_map (skeleton_set X n) (skeleton_set X m) :=
  subcomplex_map (@skeleton_mono X n m h).

Arguments skeleton_transition _ {_ _} _.

Lemma skeleton_transition_inclusion X n m (h : (n <= m)%N) :
  nat_comp (skeleton_transition X h) (skeleton_inclusion X m) =
    skeleton_inclusion X n.
Proof. apply subcomplex_map_inclusion. Qed.

Lemma skeleton_transition_compose X n m k
    (h : (n <= m)%N) (j : (m <= k)%N) (l : (n <= k)%N) :
  nat_comp (skeleton_transition X h) (skeleton_transition X j) =
    skeleton_transition X l.
Proof. apply subcomplex_map_compose. Qed.

Definition skeleton_degree_iso X n k (h : (k <= n)%N) :
  @isomorphism type_category (simplex (skeleton_set X n) k) (simplex X k).
Proof.
  refine (@Build_isomorphism type_category
    (simplex (skeleton_set X n) k) (simplex X k)
    (fun x => proj1_sig x)
    (fun x => exist _ x (skeleton_contains_degree x h)) _ _).
  - apply type_morphism_ext. intro x. apply subcomplex_simplex_ext. reflexivity.
  - apply type_morphism_ext. intro x. reflexivity.
Defined.

Lemma skeleton_exhaustive X k (x : simplex X k) :
  member (skeleton X k) k x.
Proof. apply skeleton_contains_degree. exact (leqnn k). Qed.

Lemma skeleton_union_top X :
  subcomplex_iUnion (fun n => skeleton X n) = subcomplex_top X.
Proof.
  apply subcomplex_ext. intros k x. split.
  - intros _. exact I.
  - intros _. exists k. apply skeleton_exhaustive.
Qed.

Lemma skeleton_le_iff X n (S : subcomplex X) :
  subcomplex_le (skeleton X n) S <->
    (forall k (x : simplex X k), (k <= n)%N -> member S k x).
Proof. apply generated_le. Qed.

End DPSimplicialSkeleton.
