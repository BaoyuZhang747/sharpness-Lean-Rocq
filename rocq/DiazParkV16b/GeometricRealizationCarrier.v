Module DPGeometricRealization.
Import DPSimplexCategory DPTopological.
Section Carrier.
Variable Real : realType.
Variable X : DPSimplicialSet.simplicial_set.

(** One actual topological simplex for every labelled simplex of X. This is
    the topological disjoint union of the spaces X_n(discrete) times Delta^n. *)
Definition simplex_label := {n : nat & DPSimplicialSet.simplex X n}.
Definition label_choice := [the choiceType of {classic simplex_label}].
Definition labelled_simplex (l : label_choice) : topologicalType :=
  DPTopologicalSimplex.simplex_space Real (projT1 l).
Definition pre_realization := {l : label_choice & labelled_simplex l}.
Definition pre_realization_space : topologicalType :=
  [the topologicalType of {l : label_choice & labelled_simplex l}].

Definition pre_point {n} (x : DPSimplicialSet.simplex X n)
    (t : DPTopologicalSimplex.simplex Real n) : pre_realization :=
  existT labelled_simplex (existT _ n x) t.

Lemma pre_point_continuous n (x : DPSimplicialSet.simplex X n) :
  continuous (@pre_point n x).
Proof. exact: (@existT_continuous label_choice labelled_simplex (existT _ n x)). Qed.

(** The equivalence relation is generated by ALL ordinal relations. The
    constructors state only the generating identification and closure rules. *)
Inductive realization_equivalent : pre_realization -> pre_realization -> Prop :=
| realization_equivalent_refl p : realization_equivalent p p
| realization_equivalent_sym p q :
    realization_equivalent p q -> realization_equivalent q p
| realization_equivalent_trans p q r :
    realization_equivalent p q -> realization_equivalent q r -> realization_equivalent p r
| realization_equivalent_ordinal n m (f : ordinal_map n m)
    (x : DPSimplicialSet.simplex X m) (t : DPTopologicalSimplex.simplex Real n) :
    realization_equivalent
      (pre_point (DPSimplicialSet.simplex_map X f x) t)
      (pre_point x (DPTopologicalSimplexAffine.pushforward f t)).

Definition realization_related (p q : pre_realization) :=
  `[< realization_equivalent p q >].

Lemma realization_related_refl : reflexive realization_related.
Proof. by move=> p; apply/asboolP; exact: realization_equivalent_refl. Qed.

Lemma realization_related_sym : symmetric realization_related.
Proof.
move=> p q; apply/idP/idP=> /asboolP h; apply/asboolP;
  exact: realization_equivalent_sym h.
Qed.

Lemma realization_related_trans : transitive realization_related.
Proof.
move=> p q r /asboolP hpq /asboolP hqr; apply/asboolP.
exact: realization_equivalent_trans hpq hqr.
Qed.

Definition realization_equiv := EquivRel realization_related
  realization_related_refl realization_related_sym realization_related_trans.

Definition realization_quotient := {eq_quot realization_equiv}.
Definition realization := quotient_topology [the quotType pre_realization of realization_quotient].
Definition realization_space : topologicalType :=
  [the topologicalType of quotient_topology [the quotType pre_realization of realization_quotient]].

Definition realization_class (p : pre_realization) : realization := \pi_realization p.

Lemma realization_class_eq (p q : pre_realization) :
  realization_class p = realization_class q <-> realization_equivalent p q.
Proof.
change ((\pi_realization_quotient p : realization_quotient) = \pi_realization_quotient q <->
  realization_equivalent p q).
have he := @eqmodP [the choiceType of pre_realization] realization_equiv p q.
split.
- move=> h; apply/asboolP; exact: (introT he h).
- move=> h; apply: (elimT he); by apply/asboolP.
Qed.

Lemma realization_class_surjective (z : realization) :
  exists p, realization_class p = z.
Proof. exists (repr z); exact: reprK. Qed.

Lemma realization_class_continuous : continuous realization_class.
Proof. exact: pi_continuous. Qed.

Definition characteristic {n} (x : DPSimplicialSet.simplex X n)
    (t : DPTopologicalSimplex.simplex Real n) : realization :=
  realization_class (pre_point x t).

Lemma characteristic_continuous n (x : DPSimplicialSet.simplex X n) :
  continuous (@characteristic n x).
Proof.
move=> t; apply: (@continuous_comp _ pre_realization_space realization_space
  (@pre_point n x) realization_class t);
  [exact: pre_point_continuous | exact: realization_class_continuous].
Qed.

Lemma characteristic_ordinal n m (f : ordinal_map n m)
    (x : DPSimplicialSet.simplex X m) (t : DPTopologicalSimplex.simplex Real n) :
  characteristic (DPSimplicialSet.simplex_map X f x) t =
    characteristic x (DPTopologicalSimplexAffine.pushforward f t).
Proof. apply/realization_class_eq; exact: realization_equivalent_ordinal. Qed.

Definition characteristic_map n (x : DPSimplicialSet.simplex X n) :
    hom topological_category (DPTopologicalSimplex.simplex_space Real n) realization_space :=
  continuous_map (@characteristic_continuous n x).

End Carrier.
End DPGeometricRealization.
