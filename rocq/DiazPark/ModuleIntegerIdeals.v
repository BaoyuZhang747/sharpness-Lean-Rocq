(** Every actual ideal of the integer ring is generated by one nonnegative
    integer. The zero ideal is included. *)

From mathcomp Require Import all_ssreflect all_algebra boolp intdiv.
From DiazPark Require Import ModuleInfrastructure.

Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.
Import Order.TTheory GRing.Theory Num.Theory.
Local Open Scope ring_scope.

Section IntegerIdeals.
Variable N : module_subspace [the lmodType int of int^o].

Lemma integer_ideal_abs (a : int) : N a -> N ((absz a) : int).
Proof.
  case: a => n hn; first exact hn.
  change (N (- (Negz n))). exact (@subspace_opp int _ N _ hn).
Qed.

Theorem integer_ideal_principal :
    exists d : nat, N (d : int) /\
      forall a : int, N a <-> exists q : int, a = q * (d : int).
Proof.
  destruct (pselect (exists n : nat, (0 < n)%N /\ N (n : int))) as [hn | hn].
  - have hex : exists n : nat, `[< (0 < n)%N /\ N (n : int) >].
    { destruct hn as [n hn]. exists n. exact (asboolT hn). }
    case: (ex_minnP hex) => d /asboolP [dpos hd] hmin.
    exists d. split. exact hd. intro a. split.
    + intro ha. pose r := (a %% (d : int))%Z.
      have dposz : (0 < (d : int)) by rewrite ltz_nat.
      have dneq : (d : int) != 0 by rewrite (gt_eqF dposz).
      have hr0 : 0 <= r := modz_ge0 a dneq.
      have hrd : r < (d : int) := ltz_pmod a dposz.
      have hr : N r.
      { have he : r = a - (a %/ (d : int))%Z * (d : int).
        { apply: (addIr ((a %/ (d : int))%Z * (d : int))).
          by rewrite subrK. }
        rewrite he. apply (@subspace_sub int _ N _ _ ha).
        exact (@subspace_scale int _ N (a %/ (d : int))%Z _ hd). }
      have rz : r = 0.
      { apply/eqP. apply/negPn/negP. intro rnz.
        have hnr : (0 < (absz r))%N /\ N ((absz r) : int).
        { split. by rewrite absz_gt0. exact (integer_ideal_abs hr). }
        have hm := hmin (absz r) (asboolT hnr).
        have hlt : ((absz r) < d)%N.
        { rewrite -ltz_nat (gez0_abs hr0). exact hrd. }
        by move: hm; rewrite leqNgt hlt. }
      exists (a %/ (d : int))%Z.
      have he := divz_eq a (d : int).
      change (a = (a %/ (d : int))%Z * (d : int) + r) in he.
      by rewrite rz addr0 in he.
    + intros [q ->]. exact (@subspace_scale int _ N q _ hd).
  - exists 0%N. split. exact (subspace_zero N). intro a. split.
    + intro ha. have az : a = 0.
      { apply/eqP. apply/negPn/negP. intro anz.
        apply hn. exists (absz a). split.
        - by rewrite absz_gt0.
        - exact (integer_ideal_abs ha). }
      exists 0. by rewrite az mul0r.
    + intros [q ->]. rewrite mulr0. exact (subspace_zero N).
Qed.

End IntegerIdeals.

